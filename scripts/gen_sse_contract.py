#!/usr/bin/env python3
"""从 testdata/contract/sse-events.json 生成 TS 与 Kotlin 的事件契约文件。

用法：
    python scripts/gen_sse_contract.py           # 写入生成文件
    python scripts/gen_sse_contract.py --check    # 仅校验是否最新（CI 用）
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "testdata/contract/sse-events.json"
TS_TARGET = ROOT / "web/src/app/sseEvents.generated.ts"
KT_NAMES = ROOT / "android/app/src/main/java/dev/tavernagent/mobile/domain/SseEventNames.kt"
KT_TEST = ROOT / "android/app/src/test/java/dev/tavernagent/mobile/domain/SseEventContractTest.kt"


def kstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def ts_array(name: str, items: list[str]) -> list[str]:
    lines = [f"export const {name} = ["]
    lines += [f"  {json.dumps(i, ensure_ascii=False)}," for i in items]
    lines.append("] as const;")
    return lines


def render_ts(doc: dict) -> str:
    lines = [
        "// GENERATED by scripts/gen_sse_contract.py from testdata/contract/sse-events.json.",
        "// Do not edit by hand; run `python scripts/gen_sse_contract.py`.",
    ]
    lines += ts_array("TURN_EVENT_TYPES", doc["turnEvents"])
    lines += ts_array("TERMINAL_TURN_EVENT_TYPES", doc["terminalTurnEvents"])
    lines += ts_array("DIRECTOR_EVENT_TYPES", doc["directorEvents"])
    lines.append("export type GeneratedTurnEventType = (typeof TURN_EVENT_TYPES)[number];")
    return "\n".join(lines) + "\n"


def kotlin_set(items: list[str]) -> str:
    return "setOf(" + ", ".join(kstr(i) for i in items) + ")"


def render_kotlin_names(doc: dict) -> str:
    return "\n".join([
        "package dev.tavernagent.mobile.domain",
        "",
        "/** GENERATED by scripts/gen_sse_contract.py from testdata/contract/sse-events.json. Do not edit. */",
        "object SseEventNames {",
        f"    val TURN_EVENTS: Set<String> = {kotlin_set(doc['turnEvents'])}",
        f"    val TERMINAL_TURN_EVENTS: Set<String> = {kotlin_set(doc['terminalTurnEvents'])}",
        f"    val DIRECTOR_EVENTS: Set<String> = {kotlin_set(doc['directorEvents'])}",
        "}",
        "",
    ])


def render_kotlin_test() -> str:
    return "\n".join([
        "package dev.tavernagent.mobile.domain",
        "",
        "import dev.tavernagent.mobile.data.remote.SseFrame",
        "import org.junit.Assert.assertNotNull",
        "import org.junit.Assert.assertTrue",
        "import org.junit.Test",
        "",
        "/** GENERATED by scripts/gen_sse_contract.py from testdata/contract/sse-events.json. Do not edit. */",
        "class SseEventContractTest {",
        "    @Test",
        "    fun `turn event codec recognizes contract events`() {",
        "        for (name in SseEventNames.TURN_EVENTS) {",
        '            if (name.startsWith("block.")) continue // 需要负载，无法用空数据断言',
        '            val ev = TurnEventCodec.parse(SseFrame(name, "{}", null))',
        '            assertNotNull("TurnEventCodec 未识别事件 $name", ev)',
        "        }",
        "    }",
        "",
        "    @Test",
        "    fun `terminal events are marked terminal`() {",
        "        for (name in SseEventNames.TERMINAL_TURN_EVENTS) {",
        '            assertTrue(TurnEventCodec.isTerminal(SseFrame(name, "{}", null)))',
        "        }",
        "    }",
        "}",
        "",
    ])


def main() -> int:
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    outputs = {
        TS_TARGET: render_ts(doc),
        KT_NAMES: render_kotlin_names(doc),
        KT_TEST: render_kotlin_test(),
    }
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if (p.read_text(encoding="utf-8") if p.is_file() else "") != text]
        if stale:
            print("SSE 契约生成物过期：" + ", ".join(stale))
            print("运行 python scripts/gen_sse_contract.py")
            return 1
        print("sse contract up to date")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
