#!/usr/bin/env python3
"""从 testdata/contract/markers.json 生成 Kotlin 契约测试。

标记语法是跨语言共享的：Go 与 TS 的测试直接读 JSON，Kotlin 侧由本脚本生成，
保证三端只认一份来源。

用法：
    python scripts/gen_marker_contract.py           # 写入生成的 Kotlin 测试
    python scripts/gen_marker_contract.py --check    # 仅校验是否最新（CI 用）
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "testdata/contract/markers.json"
TARGET = ROOT / "android/app/src/test/java/dev/tavernagent/mobile/domain/CardMarkerContractTest.kt"
TARGET_TS = ROOT / "web/src/lib/__tests__/markerContractCases.generated.ts"


def kstr(value: str) -> str:
    out = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    out = out.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"' + out + '"'


def klist_str(items: list[str]) -> str:
    if not items:
        return "emptyList<String>()"
    return "listOf(" + ", ".join(kstr(i) for i in items) + ")"


def kmap(values: dict[str, str]) -> str:
    return "mapOf(" + ", ".join(f"{kstr(k)} to {kstr(v)}" for k, v in values.items()) + ")"


def klist_map(items: list[dict[str, str]]) -> str:
    if not items:
        return "emptyList<Map<String, String>>()"
    return "listOf(" + ", ".join(kmap(m) for m in items) + ")"


def render(cases: list[dict]) -> str:
    lines = [
        "package dev.tavernagent.mobile.domain",
        "",
        "import org.junit.Assert.assertEquals",
        "import org.junit.Assert.assertTrue",
        "import org.junit.Test",
        "",
        "/**",
        " * GENERATED by scripts/gen_marker_contract.py from testdata/contract/markers.json.",
        " * Do not edit by hand; run `python scripts/gen_marker_contract.py`.",
        " */",
        "class CardMarkerContractTest {",
        "    private fun parse(text: String, resolvable: List<String>): List<ContentSegment> =",
        '        CardMarkerParser.parse(text) { key -> if (key in resolvable) "asset:$key" else null }',
        "",
        "    private fun images(segs: List<ContentSegment>): List<String> =",
        "        segs.filterIsInstance<ContentSegment.Image>().map { it.rawKey }",
        "",
        "    private fun hud(segs: List<ContentSegment>): List<Map<String, String>> =",
        "        segs.filterIsInstance<ContentSegment.Hud>().map { it.values }",
        "",
        "    private fun scene(segs: List<ContentSegment>): String =",
        '        segs.filterIsInstance<ContentSegment.Scene>().firstOrNull()?.title ?: ""',
        "",
        "    private fun joinedText(segs: List<ContentSegment>): String =",
        '        segs.filterIsInstance<ContentSegment.Text>().joinToString("") { it.content }',
        "",
    ]
    for case in cases:
        images = case.get("images", [])
        hud = case.get("hud", [])
        scene = case.get("scene") or ""
        var_removed = bool(case.get("varRemoved", False))
        lines += [
            "    @Test",
            f"    fun `{case['id']}`() {{",
            f"        val segs = parse({kstr(case['text'])}, {klist_str(images)})",
            f"        assertEquals({klist_str(images)}, images(segs))",
            f"        assertEquals({klist_map(hud)}, hud(segs))",
            f"        assertEquals({kstr(scene)}, scene(segs))",
        ]
        if var_removed:
            lines.append('        assertTrue(joinedText(segs).contains("[VAR:").not())')
        lines.append("    }")
        lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_ts(cases: list[dict]) -> str:
    lines = [
        "// GENERATED by scripts/gen_marker_contract.py from testdata/contract/markers.json.",
        "// Do not edit by hand; run `python scripts/gen_marker_contract.py`.",
        "export interface MarkerContractCase {",
        "  id: string;",
        "  text: string;",
        "  images: string[];",
        "  hud: Record<string, string>[];",
        "  scene: string;",
        "  varRemoved: boolean;",
        "}",
        "",
        "export const MARKER_CASES: MarkerContractCase[] = [",
    ]
    for case in cases:
        lines += [
            "  {",
            f"    id: {json.dumps(case['id'], ensure_ascii=False)},",
            f"    text: {json.dumps(case['text'], ensure_ascii=False)},",
            f"    images: {json.dumps(case.get('images', []), ensure_ascii=False)},",
            f"    hud: {json.dumps(case.get('hud', []), ensure_ascii=False)},",
            f"    scene: {json.dumps(case.get('scene') or '', ensure_ascii=False)},",
            f"    varRemoved: {'true' if case.get('varRemoved') else 'false'},",
            "  },",
        ]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    cases = json.loads(SOURCE.read_text(encoding="utf-8"))["cases"]
    generated_kotlin = render(cases)
    generated_ts = render_ts(cases)
    check = "--check" in sys.argv
    if check:
        stale = []
        if (TARGET.read_text(encoding="utf-8") if TARGET.is_file() else "") != generated_kotlin:
            stale.append(str(TARGET.relative_to(ROOT)))
        if (TARGET_TS.read_text(encoding="utf-8") if TARGET_TS.is_file() else "") != generated_ts:
            stale.append(str(TARGET_TS.relative_to(ROOT)))
        if stale:
            print("契约测试与 markers.json 不一致：" + ", ".join(stale))
            print("运行 python scripts/gen_marker_contract.py 重新生成")
            return 1
        print("marker contract up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated_kotlin, encoding="utf-8")
    TARGET_TS.parent.mkdir(parents=True, exist_ok=True)
    TARGET_TS.write_text(generated_ts, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    print(f"wrote {TARGET_TS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
