// Command gencontract 以 Go 类型为唯一源，生成 Web(TS) 与 Android(Kotlin) 的 DTO。
//
// 用法：
//
//	go run ./cmd/gencontract            # 写入生成文件
//	go run ./cmd/gencontract --check    # 仅校验是否最新（CI 用）
//
// 设计：用 reflect 读取 Go 结构体的 json tag，映射为 TS interface 与 Kotlin
// @Serializable data class。覆盖范围由下面的 manifest 显式列出——只覆盖"对外
// 契约"类型；ad-hoc map 响应不在其中（见 docs/spec/06-dto.md 的覆盖说明）。
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"

	"tavernagent/internal/application"
	"tavernagent/internal/domain"
	"tavernagent/internal/ports"
)

type entry struct {
	typ    reflect.Type
	tsName string
	ktName string
}

// manifest 是生成覆盖清单。新增类型：加入这里并在 Go 侧保证字段形状稳定。
var manifest = []entry{
	{reflect.TypeOf(domain.DirectorEvidence{}), "DirectorEvidence", "DirectorEvidenceDto"},
	{reflect.TypeOf(domain.DirectorBeat{}), "DirectorBeat", "DirectorBeatDto"},
	{reflect.TypeOf(domain.DirectorPlan{}), "DirectorPlan", "DirectorPlanDto"},
	{reflect.TypeOf(domain.DirectorBeatProgress{}), "DirectorBeatProgress", "DirectorBeatProgressDto"},
	{reflect.TypeOf(domain.DirectorState{}), "DirectorState", "DirectorStateDto"},
	{reflect.TypeOf(domain.DirectorSummary{}), "DirectorSummary", "DirectorSummaryDto"},
	{reflect.TypeOf(ports.ModelInstance{}), "ModelInstance", "ModelInstanceDto"},
	{reflect.TypeOf(domain.MemoryUsage{}), "MemoryUsage", "MemoryUsageDto"},
	{reflect.TypeOf(application.BranchView{}), "BranchView", "BranchDto"},
	{reflect.TypeOf(application.TurnCapabilities{}), "TurnCapabilities", "TurnCapabilitiesDto"},
	{reflect.TypeOf(application.AcceptResult{}), "AcceptResult", "AcceptTurnResponseDto"},
	{reflect.TypeOf(application.DeriveResponse{}), "DeriveResult", "DeriveTurnResponseDto"},
	{reflect.TypeOf(application.AssistantEditResponse{}), "AssistantEditResult", "AssistantEditResponseDto"},
	{reflect.TypeOf(domain.RelationValue{}), "RelationValue", "RelationValueDto"},
	{reflect.TypeOf(domain.ItemInstance{}), "ItemInstance", "ItemInstanceDto"},
	{reflect.TypeOf(domain.Promise{}), "PromiseItem", "PromiseDto"},
	{reflect.TypeOf(domain.CharacterMood{}), "CharacterMood", "CharacterMoodDto"},
	{reflect.TypeOf(domain.Goal{}), "Goal", "GoalDto"},
	{reflect.TypeOf(domain.Scene{}), "Scene", "SceneDto"},
	{reflect.TypeOf(domain.CharacterInfo{}), "CharacterInfo", "CharacterInfoDto"},
	{reflect.TypeOf(domain.WorldState{}), "WorldState", "WorldStateDto"},
}

var (
	tsPath = filepath.Join("web", "src", "app", "generated", "dto.generated.ts")
	ktPath = filepath.Join("android", "app", "src", "main", "java", "dev", "tavernagent", "mobile",
		"data", "remote", "dto", "GeneratedDtos.kt")
)

type field struct {
	jsonName  string
	tsType    string
	ktType    string
	optional  bool // TS: 字段可缺省
	nullable  bool // Kotlin/TS: 值可为 null
	ktDefault string
}

func main() {
	byType := map[reflect.Type]entry{}
	for _, e := range manifest {
		byType[e.typ] = e
	}

	var ts bytes.Buffer
	var kt bytes.Buffer
	writeHeaders(&ts, &kt)

	for _, e := range manifest {
		fields, err := fieldsOf(e.typ, byType, map[reflect.Type]bool{})
		if err != nil {
			fail(err)
		}
		writeTS(&ts, e, fields)
		writeKT(&kt, e, fields)
	}

	outputs := map[string][]byte{tsPath: ts.Bytes(), ktPath: kt.Bytes()}
	check := len(os.Args) > 1 && os.Args[1] == "--check"
	stale := []string{}
	for path, data := range outputs {
		if check {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(old, data) {
				stale = append(stale, path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fail(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil { //nolint:gosec // 生成物是仓库源码，非敏感文件
			fail(err)
		}
		fmt.Println("wrote", filepath.ToSlash(path))
	}
	if check {
		if len(stale) > 0 {
			fmt.Println("DTO 生成物过期：" + strings.Join(stale, ", "))
			fmt.Println("运行 go run ./cmd/gencontract")
			os.Exit(1)
		}
		fmt.Println("dto contract up to date")
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gencontract:", err)
	os.Exit(1)
}

func writeHeaders(ts, kt *bytes.Buffer) {
	ts.WriteString("// GENERATED by cmd/gencontract from Go types. DO NOT EDIT.\n")
	ts.WriteString("// 源：Go 结构体的 json tag（见 cmd/gencontract/main.go 的 manifest）。\n\n")
	kt.WriteString("// GENERATED by cmd/gencontract from Go types. DO NOT EDIT.\n")
	kt.WriteString("package dev.tavernagent.mobile.data.remote.dto\n\n")
	kt.WriteString("import kotlinx.serialization.Serializable\n\n")
}

// fieldsOf 展平结构体字段：匿名且无 tag 的嵌入字段递归展开（Go 的扁平化语义）。
func fieldsOf(t reflect.Type, byType map[reflect.Type]entry, seen map[reflect.Type]bool) ([]field, error) {
	if seen[t] {
		return nil, fmt.Errorf("递归类型 %s 暂不支持", t.Name())
	}
	seen[t] = true
	defer delete(seen, t)

	out := []field{}
	for i := 0; i < t.NumField(); i++ {
		sf := t.Field(i)
		tag := sf.Tag.Get("json")
		name, opts := parseTag(tag)
		if name == "-" {
			continue
		}
		if sf.Anonymous && name == "" {
			ft := sf.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct {
				nested, err := fieldsOf(ft, byType, seen)
				if err != nil {
					return nil, err
				}
				out = append(out, nested...)
				continue
			}
		}
		if name == "" {
			name = sf.Name
		}
		tsType, ktType, nullable, err := mapType(sf.Type, byType)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t.Name(), sf.Name, err)
		}
		optional := opts["omitempty"] || sf.Type.Kind() == reflect.Pointer
		out = append(out, field{
			jsonName:  name,
			tsType:    tsType,
			ktType:    ktType,
			optional:  optional,
			nullable:  nullable,
			ktDefault: kotlinDefault(ktType, nullable),
		})
	}
	return out, nil
}

func parseTag(tag string) (string, map[string]bool) {
	opts := map[string]bool{}
	if tag == "" {
		return "", opts
	}
	parts := strings.Split(tag, ",")
	for _, o := range parts[1:] {
		opts[o] = true
	}
	return parts[0], opts
}

func mapType(t reflect.Type, byType map[reflect.Type]entry) (string, string, bool, error) {
	nullable := false
	if t.Kind() == reflect.Pointer {
		nullable = true
		t = t.Elem()
	}
	switch t.Kind() {
	case reflect.String:
		return "string", "String", nullable, nil
	case reflect.Bool:
		return "boolean", "Boolean", nullable, nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32:
		return "number", "Int", nullable, nil
	case reflect.Int64, reflect.Uint, reflect.Uint64:
		return "number", "Long", nullable, nil
	case reflect.Float32, reflect.Float64:
		return "number", "Double", nullable, nil
	case reflect.Slice, reflect.Array:
		ets, ekt, _, err := mapType(t.Elem(), byType)
		if err != nil {
			return "", "", false, err
		}
		return ets + "[]", "List<" + ekt + ">", nullable, nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", "", false, fmt.Errorf("不支持的 map key 类型 %s", t.Key())
		}
		vts, vkt, _, err := mapType(t.Elem(), byType)
		if err != nil {
			return "", "", false, err
		}
		return "Record<string, " + vts + ">", "Map<String, " + vkt + ">", nullable, nil
	case reflect.Struct:
		if t == reflect.TypeOf(time.Time{}) {
			return "string", "String", nullable, nil
		}
		if e, ok := byType[t]; ok {
			return e.tsName, e.ktName, nullable, nil
		}
		return "", "", false, fmt.Errorf("结构体 %s 不在 manifest 中（请加入清单或改用受支持类型）", t.Name())
	default:
		return "", "", false, fmt.Errorf("不支持的类型 %s", t)
	}
}

func kotlinDefault(ktType string, nullable bool) string {
	if nullable {
		return "null"
	}
	switch {
	case ktType == "String":
		return `""`
	case ktType == "Boolean":
		return "false"
	case ktType == "Int":
		return "0"
	case ktType == "Long":
		return "0L"
	case ktType == "Double":
		return "0.0"
	case strings.HasPrefix(ktType, "List<"):
		return "emptyList()"
	case strings.HasPrefix(ktType, "Map<"):
		return "emptyMap()"
	default:
		// 生成的嵌套类型：所有字段都有默认值，因此可以用无参构造。
		return ktType + "()"
	}
}

func writeTS(b *bytes.Buffer, e entry, fields []field) {
	fmt.Fprintf(b, "export interface %s {\n", e.tsName)
	for _, f := range fields {
		typ := f.tsType
		if f.nullable {
			typ += " | null"
		}
		opt := ""
		if f.optional {
			opt = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", f.jsonName, opt, typ)
	}
	b.WriteString("}\n\n")
}

func writeKT(b *bytes.Buffer, e entry, fields []field) {
	fmt.Fprintf(b, "@Serializable\ndata class %s(\n", e.ktName)
	for _, f := range fields {
		typ := f.ktType
		if f.nullable {
			typ += "?"
		}
		fmt.Fprintf(b, "    val %s: %s = %s,\n", f.jsonName, typ, f.ktDefault)
	}
	b.WriteString(")\n\n")
}
